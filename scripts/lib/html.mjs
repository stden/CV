// Shared page frame. Every page is built here so that metadata, navigation and
// relative paths are defined once.

export const AUTHOR = 'Denis Stepulenok';
export const SECTIONS = [
  { id: 'overview', label: 'Overview' },
  { id: 'experience', label: 'Experience' },
  { id: 'projects', label: 'Projects' },
  { id: 'skills', label: 'Skills' },
  { id: 'architecture', label: 'Architecture' },
  { id: 'education', label: 'Education' },
  { id: 'contact', label: 'Contact' }
];

export function escapeHtml(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// Relative path from a page to the site root: 'cv/x/' -> '../../', 'tech/java.html' -> '../'.
export function prefixFor(pagePath) {
  const parts = pagePath.split('/').filter(Boolean);
  const depth = pagePath.endsWith('/') ? parts.length : parts.length - 1;
  return '../'.repeat(depth);
}

export function canonicalUrl(site, pagePath) {
  return `${site.origin}${site.basePath}${pagePath}`;
}

function header(prefix, defaultCvPdf) {
  const nav = SECTIONS.map((section) => `<a href="${prefix}#${section.id}">${section.label}</a>`).join('\n        ');
  return `<header class="site-header">
  <div class="container site-header__inner">
    <a class="brand" href="${prefix || './'}">${AUTHOR}</a>
    <nav aria-label="Sections">
        ${nav}
    </nav>
    <div class="site-header__actions">
      <a class="button button--primary" href="${prefix}downloads/${escapeHtml(defaultCvPdf)}" download>Download CV</a>
      <button type="button" class="icon-button js-only" data-theme-toggle aria-label="Switch to dark theme">
        <span aria-hidden="true">◐</span>
      </button>
    </div>
  </div>
</header>`;
}

function footer(prefix, site, github) {
  return `<footer class="site-footer">
  <div class="container">
    <p>Last updated ${site.updated}. Source: <a href="${github}" rel="noopener">github.com/stden/CV</a>.
    Plain HTML and CSS, generated by <code>npm run build</code>.</p>
    <p><a href="${prefix}cv/full/">Full CV online</a> · <a href="${prefix}downloads/Denis-Stepulenok-Full-CV.pdf" download>Full CV as PDF</a></p>
  </div>
</footer>`;
}

export function documentShell({ title, description, pagePath, prefix, site, body, jsonLd = [], bodyClass = '', ogType = 'profile', robots = 'index, follow' }) {
  const url = canonicalUrl(site, pagePath);
  const image = `${site.origin}${site.basePath}assets/images/social-card.png`;
  const schemas = jsonLd.map((item) => `<script type="application/ld+json">${JSON.stringify(item).replace(/</g, '\\u003c')}</script>`);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<meta name="description" content="${escapeHtml(description)}">
<meta name="author" content="${AUTHOR}">
<meta name="robots" content="${robots}">
<link rel="canonical" href="${url}">
<meta property="og:site_name" content="${AUTHOR}">
<meta property="og:type" content="${ogType}">
<meta property="og:title" content="${escapeHtml(title)}">
<meta property="og:description" content="${escapeHtml(description)}">
<meta property="og:url" content="${url}">
<meta property="og:image" content="${image}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${escapeHtml(title)}">
<meta name="twitter:description" content="${escapeHtml(description)}">
<meta name="twitter:image" content="${image}">
<link rel="icon" href="${prefix}favicon.ico">
<link rel="preload" href="${prefix}assets/fonts/inter-latin.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="${prefix}assets/css/site.css">
<script>
(function () {
  try {
    var saved = localStorage.getItem('cv-theme');
    if (saved === 'light' || saved === 'dark') document.documentElement.dataset.theme = saved;
  } catch (error) {}
})();
</script>
${schemas.join('\n')}
</head>
<body class="${bodyClass}">
<a class="skip-link" href="#main">Skip to content</a>
${header(prefix, site.defaultCvPdf)}
<main id="main">
${body}
</main>
${footer(prefix, site, 'https://github.com/stden/CV')}
<script src="${prefix}assets/js/site.js" defer></script>
</body>
</html>
`;
}
